def calc_metrics(pairs, rf=0.017):
    """单只基金指标计算，与 v1 逻辑完全一致"""
    if len(pairs) < 20:
        return {}

    def slice_from(start):
        return [(d, n) for d, n in pairs if d >= start]

    def nav_before(date_str):
        """找到 date_str 之前（含）最近一个交易日的净值"""
        for d, n in reversed(pairs):
            if d <= date_str:
                return (d, n)
        return None

    def daily_rets(ps):
        ns = [p[1] for p in ps]
        return [(ns[i]-ns[i-1])/ns[i-1] for i in range(1, len(ns)) if ns[i-1] > 0]

    def period_ret_from(base_nav, latest_nav):
        """从基准净值到最新净值的收益率"""
        if not base_nav or base_nav <= 0:
            return 0
        return round((latest_nav / base_nav - 1) * 100, 2)

    def period_ret(ps):
        if len(ps) < 2: return 0
        return round((ps[-1][1]/ps[0][1] - 1) * 100, 2)

    def ann_ret(ps):
        if len(ps) < 2: return None
        days = (datetime.strptime(ps[-1][0], '%Y-%m-%d') - datetime.strptime(ps[0][0], '%Y-%m-%d')).days
        if days < 30: return None
        return (ps[-1][1]/ps[0][1])**(365/days) - 1

    def mdd(ps):
        peak, worst = ps[0][1], 0
        for _, n in ps:
            if n > peak: peak = n
            dd = (peak - n) / peak
            if dd > worst: worst = dd
        return -worst

    def vol(rets):
        if len(rets) < 5: return None
        mu = sum(rets)/len(rets)
        return math.sqrt(sum((r-mu)**2 for r in rets)/len(rets)) * math.sqrt(250)

    def sharpe(rets, ar):
        v = vol(rets)
        return (ar - rf) / v if v else None

    def r(v, d=4):
        return round(v, d) if v is not None else None

    latest_nav = pairs[-1][1]
    latest_date = pairs[-1][0]
    ld = datetime.strptime(latest_date, '%Y-%m-%d')  # 以最新净值日期为锚点

    # 各区间起点：基于最新净值日期往回算，找目标日期当天或之前最近的交易日
    ytd_base = nav_before(f'{ld.year - 1}-12-31')
    d1y  = (ld - timedelta(days=365)).strftime('%Y-%m-%d')
    d2y  = (ld - timedelta(days=730)).strftime('%Y-%m-%d')
    d3y  = (ld - timedelta(days=1095)).strftime('%Y-%m-%d')
    d6m  = (ld - relativedelta(months=6)).strftime('%Y-%m-%d')
    d3m  = (ld - relativedelta(months=3)).strftime('%Y-%m-%d')
    d2m  = (ld - relativedelta(months=2)).strftime('%Y-%m-%d')
    d1m  = (ld - relativedelta(months=1)).strftime('%Y-%m-%d')
    d2w  = (ld - timedelta(days=14)).strftime('%Y-%m-%d')
    d1w  = (ld - timedelta(days=7)).strftime('%Y-%m-%d')

    b1y  = nav_before(d1y)
    b2y  = nav_before(d2y)
    b3y  = nav_before(d3y)
    b6m  = nav_before(d6m)
    b3m  = nav_before(d3m)
    b2m  = nav_before(d2m)
    b1m  = nav_before(d1m)
    b2w  = nav_before(d2w)
    b1w  = nav_before(d1w)

    # 用于回撤和夏普的区间切片
    p1y  = slice_from(d1y)
    p2y  = slice_from(d2y)
    pytd_start = f'{ld.year}-01-01'
    pytd = slice_from(pytd_start)
    # YTD 切片需要把上年末净值加入用于回撤/夏普计算
    if ytd_base and ytd_base[0] < pytd_start:
        pytd = [ytd_base] + pytd

    ar1y = ann_ret(p1y)
    dr1y = daily_rets(p1y)
    ar_ytd = ann_ret(pytd)
    dr_ytd = daily_rets(pytd)
    ytd_mdd = mdd(pytd) if len(pytd) > 5 else 0
    mdd_2y_val = mdd(p2y) if len(p2y) > 20 else 0

    return {
        'nav':     latest_nav,
        'nd':      latest_date,
        'r1d':     round((pairs[-1][1]/pairs[-2][1] - 1) * 100, 4) if len(pairs) >= 2 else 0,
        'r1m':     period_ret_from(b1m[1] if b1m else 0, latest_nav),
        'r3m':     period_ret_from(b3m[1] if b3m else 0, latest_nav),
        'r6m':     period_ret_from(b6m[1] if b6m else 0, latest_nav),
        'r1y':     period_ret_from(b1y[1] if b1y else 0, latest_nav),
        'r2y':     period_ret_from(b2y[1] if b2y else 0, latest_nav),
        'r3y':     period_ret_from(b3y[1] if b3y else 0, latest_nav),
        'rytd':    period_ret_from(ytd_base[1] if ytd_base else 0, latest_nav),
        'r1w':     period_ret_from(b1w[1] if b1w else 0, latest_nav),
        'r2w':     period_ret_from(b2w[1] if b2w else 0, latest_nav),
        'r2m':     period_ret_from(b2m[1] if b2m else 0, latest_nav),
        'mdd':     r(mdd(p1y) * 100, 2) if len(p1y) > 20 else 0,
        'mdd_ytd': r(ytd_mdd * 100, 2) if ytd_mdd else 0,
        'mdd_2y':  r(mdd_2y_val * 100, 2) if mdd_2y_val else 0,
        'sr':      r(sharpe(dr1y, ar1y), 2) if ar1y else 0,
        'sr_ytd':  r(sharpe(dr_ytd, ar_ytd), 2) if ar_ytd else 0,
        'h':       [round(n, 4) for _, n in pairs[-90:]],
    }



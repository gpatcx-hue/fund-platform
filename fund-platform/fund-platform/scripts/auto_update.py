def clean_ad_text(text):
    if not text:
        return text
    for marker in ['📈', '📣']:
        idx = text.find(marker)
        if idx >= 0:
            text = text[idx:]
            break
    lines = text.split('\n')
    cleaned = []
    for line in lines:
        stripped = line.strip()
        if stripped.startswith('|') and '---' in stripped:
            continue
        if stripped.startswith('|') and stripped.endswith('|'):
            continue
        if stripped.startswith('###') or stripped.startswith('##'):
            continue
        if stripped == '---':
            continue
        cleaned.append(line)
    return '\n'.join(cleaned).strip()



def _build_lookups():
    """从 CATEGORIES 构建全局查找表，避免重复遍历"""
    all_codes = []        # 去重后的所有基金代码
    code_to_cat = {}      # 代码 → 所属赛道
    fund_info = {}        # 代码 → 元数据
    own_config = {}       # 赛道 → [自家代码(不含.OF)]

    seen = set()
    for cat_id in CAT_ORDER:
        cat = CATEGORIES.get(cat_id)
        if not cat:
            continue
        own_config[cat_id] = []
        for code, info in cat["funds"].items():
            if code not in seen:
                all_codes.append(code)
                seen.add(code)
            code_to_cat[code] = cat_id
            fund_info[code] = info
            if info.get("own"):
                own_config[cat_id].append(info.get('dc', code.replace('.OF', '')))

    return all_codes, code_to_cat, fund_info, own_config



    signals = _market_signals(market_data)
    print(f'  市场信号: 债={signals["bond"]:.0f} 股={signals["equity"]:.0f} 转债={signals["convert"]:.0f}')

    candidates = []

    for cat_id, cat in CATEGORIES.items():
        cat_codes = list(cat['funds'].keys())
        cat_m = {c: metrics_map.get(c, {}) for c in cat_codes}

        def pctl(key, code, high_better=True):
            v = cat_m.get(code, {}).get(key)
            if v is None: return None
            vals = [cat_m[c].get(key) for c in cat_codes if cat_m[c].get(key) is not None]
            if len(vals) < 5: return None
            if high_better:
                return round(sum(1 for x in vals if x <= v) / len(vals) * 100, 1)
            else:
                return round(sum(1 for x in vals if abs(x) >= abs(v)) / len(vals) * 100, 1)

        for code, info in cat['funds'].items():
            if not info.get('own'):
                continue
            m = metrics_map.get(code, {})
            if not m or m.get('nav', 0) == 0:
                continue

            # --- 支柱1: 产品实力 (满分50) ---
            p3m  = pctl('r3m', code, True) or 0
            pytd = pctl('rytd', code, True) or 0
            pmdd = pctl('mdd_ytd', code, False) or 0
            psr  = pctl('sr', code, True) or 0
            pillar1 = (p3m / 100 * 12) + (pytd / 100 * 8) + (pmdd / 100 * 15) + (psr / 100 * 15)

            # --- 支柱2: 市场顺风 (满分30) ---
            sens = MARKET_SENSITIVITY.get(cat_id, {'bond': 0.5, 'equity': 0.3, 'convert': 0.2})
            market_score_raw = (
                sens['bond'] * signals['bond'] +
                sens['equity'] * signals['equity'] +
                sens['convert'] * signals['convert']
            )
            pillar2 = market_score_raw * 30 / 100

            # --- 支柱3: 动量反转 (满分20) ---
            p2w = pctl('r2w', code, True) or 0

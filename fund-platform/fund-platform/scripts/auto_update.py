def rank_per_category(metrics_map):
    """对每个赛道的自家产品计算同类排名"""
    rankings = {}  # { cat_id: { own_code: { metric: rank_info } } }

    for cat_id in CAT_ORDER:
        cat = CATEGORIES.get(cat_id)
        if not cat:
            continue

        cat_codes = list(cat["funds"].keys())
        cat_metrics = [metrics_map.get(c, {}) for c in cat_codes]
        cat_valid = [(c, m) for c, m in zip(cat_codes, cat_metrics) if m]

        own_codes = [c for c, info in cat["funds"].items() if info.get("own")]
        rankings[cat_id] = {}

        for own_code in own_codes:
            own_m = metrics_map.get(own_code, {})
            if not own_m:
                continue

            rank_result = {}
            for key, label, high_better in [
                ('r1y', '近1年收益', True),
                ('rytd', 'YTD收益', True),
                ('sr', '夏普比率', True),
                ('mdd', '最大回撤', False),
            ]:
                own_val = own_m.get(key)
                if own_val is None:
                    continue
                vals = [m.get(key) for _, m in cat_valid if m.get(key) is not None]
                if not vals:
                    continue
                if high_better:
                    r = sum(1 for v in vals if v > own_val) + 1
                    pctl = sum(1 for v in vals if v <= own_val) / len(vals) * 100
                else:
                    r = sum(1 for v in vals if abs(v) < abs(own_val)) + 1
                    pctl = sum(1 for v in vals if abs(v) >= abs(own_val)) / len(vals) * 100
                rank_result[key] = {
                    'rank': r, 'total': len(vals), 'pctl': round(pctl, 1), 'label': label,
                }
            rankings[cat_id][own_code] = rank_result

    return rankings



def _market_signals(market_data):
    """从市场数据提取债/股/转债信号（0-100）"""
    def _to_signal(r1w):
        # 周涨幅映射: -1% → 0, 0% → 50, +1% → 100
        return max(0, min(100, 50 + r1w * 50))

    bond_vals = [market_data[k]['r1w'] for k in ['511010.SH', '511260.SH'] if k in market_data]
    equity_vals = [market_data[k]['r1w'] for k in ['510300.SH', '510500.SH'] if k in market_data]
    convert_vals = [market_data[k]['r1w'] for k in ['511380.SH'] if k in market_data]

    return {
        'bond':    _to_signal(sum(bond_vals) / len(bond_vals)) if bond_vals else 50,
        'equity':  _to_signal(sum(equity_vals) / len(equity_vals)) if equity_vals else 50,
        'convert': _to_signal(sum(convert_vals) / len(convert_vals)) if convert_vals else 50,
    }


def select_top3(metrics_map, market_data):
    """从15只自家产品中动态选出3只推荐到首页"""

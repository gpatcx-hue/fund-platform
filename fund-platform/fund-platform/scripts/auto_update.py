def _build_adj_nav(raw_records):
    """从 DWJZ + LJJZ 精确重建复权净值
    普通基金：用 DWJZ+LJJZ 检测分红，重建复权净值
    ETF/特殊基金：LJJZ < DWJZ 时，直接用 DWJZ 算收益率（无需复权）
    """
    if not raw_records:
        return []
    n = len(raw_records)

    # 检测是否为 ETF：最新 LJJZ < DWJZ 的一半
    latest_dwjz = raw_records[-1][1]
    latest_ljjz = raw_records[-1][2]
    is_etf = latest_ljjz < latest_dwjz * 0.5

    if is_etf:
        # ETF 直接用 DWJZ，不做复权
        return [(r[0], round(r[1], 6)) for r in raw_records]

    # 普通基金：DWJZ + LJJZ 重建复权净值
    adj = [0.0] * n
    adj[-1] = latest_dwjz

    for i in range(n - 2, -1, -1):
        dwjz_t   = raw_records[i][1]
        dwjz_t1  = raw_records[i + 1][1]
        ljjz_t   = raw_records[i][2]
        ljjz_t1  = raw_records[i + 1][2]

        dividend = (ljjz_t1 - ljjz_t) - (dwjz_t1 - dwjz_t)
        if dividend < -0.0001:
            dividend = 0

        if dwjz_t > 0:
            daily_ret = (dwjz_t1 + dividend) / dwjz_t - 1
        else:
            daily_ret = 0

        adj[i] = adj[i + 1] / (1 + daily_ret) if daily_ret != -1 else adj[i + 1]

    return [(raw_records[i][0], round(adj[i], 6)) for i in range(n)]


